function seedFor(name){let h=2166136261;for(const c of name){h^=c.charCodeAt(0);h=Math.imul(h,16777619)}return h>>>0}
export function knockoutDetailSketch(creature){
 const base=creatureArtProfile(creature).base;
 const traits=knockoutSketchTraits[base]||[];
 if(!traits.length||tamingCategory(creature)!=='knockout')return [];
 // Deterministic but restrained wrinkles and scale creases on body, not fake stats.
 const seed=seedFor(creature);
 const marks=Array.from({length:7},(_,i)=>{
  const x=255+((seed+i*61)%230);
  const y=219+(((seed>>>((i%4)*6))+i*17)%55);
  const dx=9+((seed+i*13)%15),dy=(i%2?12:-11);
  return `M${x} ${y} q${dx} ${dy} ${dx+14} 4`;
 });
 return [...traits.map(key=>paths[key]).filter(Boolean),...marks];
}
